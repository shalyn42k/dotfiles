-- input.lua — наш оверрайд ввода поверх настроек апстрима.
--
-- Живёт отдельным файлом, а не внутри overrides.lua, по одной причине:
-- настройки рига переприменяются на горячем свитче (settings-runtime.lua),
-- а апстрим держит general/decoration/input/misc ОДНИМ вызовом hl.config.
-- Переприменить его — значит вернуть input апстрима, то есть снова сломать
-- смену языка. Поэтому наш input отделён и накладывается после.
--
-- Класть его в overrides.lua тоже нельзя: тот файл вешает бинды, а
-- ре-бинд стекается — переприменение наплодило бы дубли.

-- Апстрим ставит ОДНУ раскладку ("us") — переключать нечего, поэтому смена
-- языка в риге просто не работала. И комбо у него своё (alt+shift), то есть
-- даже с двумя раскладками мышечная память из caelestia не сработала бы.
-- Значения те же, что в profiles/caelestia/hypr/hyprland/input.lua.
hl.config({
    input = {
        kb_layout  = "pl, ru",
        kb_options = "grp:win_space_toggle",
    },
})
