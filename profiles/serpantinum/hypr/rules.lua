-- Правила окон рига serpantinum.
--
-- Зачем файл вообще появился: у рига их не было НИ ОДНОГО, а бинды §2.3
-- (SUPER+Z/X/C/V в overrides.lua) устроены как «тоггл, если приложение уже
-- запущено, иначе запуск». Ветка тоггла работала, ветка запуска — нет:
-- запущенное окно некому было отправить в спец-воркспейс, и приложение
-- открывалось на текущем. Поймано на живой сессии 2026-09-06.
--
-- У caelestia те же четыре назначения лежат в hypr/hyprland/rules.lua; здесь
-- своя копия, а не шаринг чужого файла — риг не должен зависеть от другого
-- рига, он обязан работать и когда соседа в системе нет.
--
-- Имена спец-воркспейсов обязаны совпадать с тремя местами рига:
-- overrides.lua (toggle_special), scripts/specialcycle.fish (список для цикла)
-- и этим файлом. Расхождение выглядит как «приложение уехало не туда».

-- Класс, а не имя процесса: Electron-приложения (vesktop, obsidian) называют
-- окно иначе, чем бинарь. Значения сверены с живым `hyprctl clients` на этой
-- машине 2026-09-06.
--
-- silent НЕ ставим намеренно. Правило срабатывает только на ЗАПУСКЕ (окна ещё
-- нет), а запуск — это всегда «хочу увидеть приложение». С silent окно уехало
-- бы в невидимый спец-воркспейс, и комбу пришлось бы жать второй раз.
hl.window_rule({ match = { class = "feishin" },              workspace = "special:music" })
hl.window_rule({ match = { class = "(?i)vesktop" },          workspace = "special:communication" })
-- Obsidian переименовал класс в md.obsidian.Obsidian; шаблон покрывает и
-- прежнее имя — та же правка, что у caelestia (коммит 659b536).
hl.window_rule({ match = { class = "(?i).*obsidian.*" },     workspace = "special:todo" })
hl.window_rule({ match = { class = "com.ayugram.desktop" },  workspace = "special:messanger" })
